"""Stable public service interfaces. Implementations may change behind these protocols."""

from __future__ import annotations

from typing import Any, BinaryIO, Protocol


class RubricService(Protocol):
    def list(self, *, query: str | None = None) -> dict[str, Any]: ...
    def get(self, rubric_id: str) -> dict[str, Any]: ...
    def create(self, payload: dict[str, Any], actor_id: str) -> dict[str, Any]: ...


class BatchService(Protocol):
    def list(self, **filters: Any) -> dict[str, Any]: ...
    def get(self, batch_id: str) -> dict[str, Any]: ...
    def create(self, payload: dict[str, Any], actor_id: str) -> dict[str, Any]: ...
    def start(
        self, batch_id: str, payload: dict[str, Any], sample: int | None
    ) -> dict[str, Any]: ...


class SubmissionService(Protocol):
    def retry(self, submission_id: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    def patch(self, submission_id: str, payload: dict[str, Any]) -> dict[str, Any]: ...


class ReviewService(Protocol):
    def open(self, submission_id: str, actor_id: str) -> dict[str, Any]: ...
    def save_criterion(
        self, submission_id: str, criterion_id: str, payload: dict[str, Any]
    ) -> dict[str, Any]: ...
    def confirm(self, submission_id: str, actor_id: str, version: int) -> dict[str, Any]: ...


class SettingsService(Protocol):
    def get_ai(self) -> dict[str, Any]: ...
    def put_ai(self, payload: dict[str, Any]) -> dict[str, Any]: ...


class FileStore(Protocol):
    def save(self, *, batch_id: str, sha256: str, extension: str, stream: BinaryIO) -> str: ...
